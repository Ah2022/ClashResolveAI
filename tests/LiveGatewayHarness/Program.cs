owner.Calls.Clear();gateway.Submit(LiveOperation.Clear);gateway.Submit(LiveOperation.Refresh);gateway.Execute(app);
Check(owner.Calls.Contains("clear:A") && !owner.Calls.Contains("refresh:A"),"Clear renews generation and rejects pre-clear queued work");
gateway.Submit(LiveOperation.Refresh);app.ActiveUIDocument.Document.IsValidObject=false;gateway.Execute(app);
Check(!owner.Calls.Contains("refresh:A"),"Invalid native document rejects API work");
app.ActiveUIDocument.Document.IsValidObject=true;
gateway.Submit(LiveOperation.Refresh);gateway.Close("A");gateway.Execute(app);
Check(gateway.QueueDepth==0 && owner.Calls.Contains("close:A"),"Confirmed closure removes queued work and session state");
gateway.Activate("A");
gateway.Submit(LiveOperation.Selection);app.ActiveUIDocument.Document.IsFamilyDocument=true;gateway.Execute(app);
