Check(owner.Calls.Contains("refresh:A"),"Retried wake eventually dispatches retained work");
owner.HasPendingWork=true;owner.Calls.Clear();DispatcherTimer.Latest.Fire();gateway.Execute(app);
Check(owner.Calls.Contains("advance:A"),"The shared gateway advances live geometry work");
