using ClashResolveAI.Core;
using ClashResolveAI.LiveMonitor;
using ClashResolveAI.Services;
using ClashResolveAI.Inspection;
using System.Windows.Threading;

int passed=0;
void Check(bool condition,string message){if(!condition)throw new Exception(message);passed++;Console.WriteLine("PASS "+message);}
var owner=new LiveMonitorService();var app=new UIApplication();
using var gateway=new RevitLiveMonitorGateway(owner);
gateway.Activate("A");long a=gateway.Generation("A");
