clash.SessionGeneration=gateway.Generation("A");gateway.Submit(LiveOperation.Snapshot,"pair",3);gateway.Execute(app);
Check(ClashSnapshotStore.Instance.Latest?.DocumentKey=="A" && ClashSnapshotStore.Instance.Latest.SessionGeneration==gateway.Generation("A"),"Snapshot publication carries its validated document and generation");
