Check(!owner.Calls.Any(c=>c.StartsWith("mode:")),"A delayed mode change cannot affect a different active document");
gateway.Dispose();Check(!gateway.Submit(LiveOperation.Refresh) && !DispatcherTimer.Latest.Started,"Disposed gateway rejects submissions and stops its timer");
Console.WriteLine($"{passed} gateway dispatch checks passed.");
