Check(!ClashViewNavigation.DeferredValid!(),"Session reset invalidates deferred navigation completion");
clash.SessionGeneration=gateway.Generation("A");gateway.Submit(LiveOperation.Inspect,"pair",2);gateway.Execute(app);
Check(InspectionHandler.Calls==0,"Geometry revision mismatch rejects inspection");
